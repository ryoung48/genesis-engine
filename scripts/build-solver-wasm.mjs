// Compiles assembly/solver-kernels.ts (AssemblyScript) and writes the module, base64-encoded, to
// src/model/climatev2/vendor/solver-kernels.wasm.js, so Node, vitest and the browser all load it the same way.
import { execFileSync } from "node:child_process"
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const wasmPath = path.join(root, "node_modules", ".cache", "solver-kernels.wasm")
fs.mkdirSync(path.dirname(wasmPath), { recursive: true })
const asc = path.join(root, "node_modules", "assemblyscript", "bin", "asc.js")
execFileSync(
	process.execPath,
	[
		asc,
		path.join(root, "assembly", "solver-kernels.ts"),
		"-O3",
		"--runtime",
		"stub",
		"--importMemory",
		"--noAssert",
		"--outFile",
		wasmPath,
	],
	{ stdio: "inherit" },
)
const bytes = fs.readFileSync(wasmPath)
const module = new WebAssembly.Module(bytes)
const imports = WebAssembly.Module.imports(module).map((i) => `${i.module}.${i.name}`)
const exports = WebAssembly.Module.exports(module).map((e) => e.name)
const out = path.join(root, "src", "model", "climatev2", "vendor", "solver-kernels.wasm.js")
fs.writeFileSync(
	out,
	`// Generated by scripts/build-solver-wasm.mjs from assembly/solver-kernels.ts (a port of solver.js's relax and residual kernels,
// GPL-3.0, see LICENSE). Do not edit: run pnpm build:solver-wasm.
// imports: ${imports.join(", ")}; exports: ${exports.join(", ")}
export const SOLVER_WASM_BASE64 = "${bytes.toString("base64")}";
`,
)
console.log(`${bytes.length} bytes → ${path.relative(root, out)}; imports ${imports.join(", ")}; exports ${exports.join(", ")}`)
